#!/usr/bin/env node
// Regenerates migrations/0002_seed_existing_content.sql from the website's
// built-in facilities and testimonials (src/data/*.ts), so the admin dashboard
// starts out showing — and able to edit — everything already on the site.
//
// You normally never need to run this: the generated .sql file is committed.
// Re-run it only if you change src/data/facilities.ts or testimonials.ts and
// want a fresh seed for a NEW database:
//   node scripts/generate-seed.mjs

import { createServer } from "vite";
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

// Use Vite (already a project dependency) to load the TypeScript data files —
// it understands the "@/" alias and the photo imports for us.
const vite = await createServer({
  configFile: false,
  root,
  appType: "custom",
  logLevel: "silent",
  server: { middlewareMode: true },
  resolve: { alias: { "@": join(root, "src") } },
});
const { facilities } = await vite.ssrLoadModule("/src/data/facilities.ts");
const { testimonials } = await vite.ssrLoadModule("/src/data/testimonials.ts");
await vite.close();

const q = (v) =>
  v === undefined || v === null || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`;
const n = (v) => (typeof v === "number" ? String(v) : "NULL");

const lines = [
  "-- Seeds the admin database with the content already on the website.",
  "-- Safe to run more than once (existing rows are left alone).",
  "-- Generated by scripts/generate-seed.mjs — do not edit by hand.",
  "",
];

facilities.forEach((f, i) => {
  lines.push(
    `INSERT OR IGNORE INTO facilities (slug, name, region, lat, lon, short_description, location_note, description, sort_order) VALUES (` +
      [
        q(f.slug),
        q(f.name),
        q(f.region),
        n(f.coordinates[0]),
        n(f.coordinates[1]),
        q(f.shortDescription),
        q(f.locationNote),
        q(f.description.join("\n\n")),
        String(i + 1),
      ].join(", ") +
      `);`,
  );
});
lines.push("");

testimonials.forEach((t, i) => {
  lines.push(
    `INSERT OR IGNORE INTO testimonials (legacy_id, quote, name, title, facility_slug, sort_order) VALUES (` +
      [q(t.id), q(t.quote), q(t.name), q(t.title), q(t.facilitySlug), String(i + 1)].join(", ") +
      `);`,
  );
});
lines.push("");

const out = join(root, "migrations", "0002_seed_existing_content.sql");
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}: ${facilities.length} facilities, ${testimonials.length} testimonials.`);
